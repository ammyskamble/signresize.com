import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import {transform} from 'esbuild';
const source=fs.readFileSync('src/components/ScrollToTop.astro','utf8');
const {code}=await transform(source.match(/<script>([\s\S]*?)<\/script>/)[1],{loader:'ts'});
const events={},calls=[],button={hidden:true,addEventListener:(k,v)=>events['button:'+k]=v},footer={addEventListener:(k,v)=>events['footer:'+k]=v};
let reduced=false;
const window={scrollY:0,scrollTo:v=>calls.push(v),matchMedia:()=>({matches:reduced}),addEventListener:(k,v)=>events[k]=v};
vm.runInNewContext(code,{window,document:{getElementById:id=>id==='scroll-to-top-btn'?button:footer}});
assert.equal(button.hidden,true);
window.scrollY=400;events.scroll();assert.equal(button.hidden,false);
events['button:click']({preventDefault(){}});assert.equal(calls.length,1);assert.equal(calls[0].behavior,'smooth');
reduced=true;events['footer:click']({preventDefault(){}});assert.equal(calls[1].behavior,'instant');
window.scrollY=0;events.scroll();assert.equal(button.hidden,true);
window.scrollY=500;events.pageshow();assert.equal(button.hidden,false);
assert.ok(!events['button:touchend']);
assert.ok(!fs.readFileSync('src/styles/home-workspace.css','utf8').includes('.home-workspace #scroll-to-top-btn { display: none; }'));
console.log('PASS: visibility, restored scroll position, one action per click, footer action and reduced motion.');
