import assert from 'node:assert/strict';
import fs from 'node:fs';
import { build } from 'esbuild';
const html = fs.readFileSync('dist/index.html', 'utf8');
assert.equal((html.match(/<h1\b/g) || []).length, 1);
assert.equal((html.match(/id="exam-specs"/g) || []).length, 1, 'One unified directory');
assert.equal((html.match(/id="exam-directory-search"/g) || []).length, 1);
assert.equal((html.match(/data-directory-tab=/g) || []).length, 6);
assert.equal((html.match(/aria-label="Application deadlines"/g) || []).length, 1, 'No duplicated deadline banner');
assert.ok(!html.includes('Quick Specification Matrix') && !html.includes('Verified Preset Directory'), 'Old duplicated directories removed');
assert.ok(!html.includes('Supported Exam &amp; Portal Presets Directory'), 'Homepage footer must not add a second exam directory');
assert.match(html, /<details[^>]*class="custom-export-settings[^>]*><summary/);
assert.ok(!/<details[^>]*class="custom-export-settings[^>]*\bopen\b/.test(html), 'Advanced settings start collapsed');
assert.ok(!html.includes('Signature Resizer Engine'), 'Decorative terminal removed from the homepage');
assert.match(html, /<h1\b[^>]*>Resize Signature Online[\s\S]*?10 to 20 KB\.<\/span><\/h1>/, 'Signature hero keeps a descriptive main heading with the tool and target size');
const presetRows = [...html.matchAll(/<tr\b[^>]*data-directory-row[^>]*>/g)].map(m => m[0]);
assert.ok(presetRows.length > 90, 'Full preset data remains in server-rendered HTML');
assert.equal(presetRows.filter(row => !/\bhidden(?:\s|>|=)/.test(row)).length, 10, 'Only ten presets initially visible');
const schemas = [...html.matchAll(/<script type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/g)].map(m => JSON.parse(m[1]));
assert.equal(schemas.filter(s => s['@type'] === 'FAQPage').length, 1, 'One FAQ schema');
assert.ok(schemas.some(s => (Array.isArray(s['@type']) ? s['@type'] : [s['@type']]).includes('SoftwareApplication')));
const faq = schemas.find(s => s['@type'] === 'FAQPage');
assert.ok(faq.mainEntity.length > 0);
assert.ok(!html.includes('Before and after processing') && html.includes('Portal upload diagnostics'));
assert.equal((html.match(/id="exam-day-toolkit"/g) || []).length, 1, 'One visible exam-day toolkit');
const journey = ['id="tool-workspace"', 'id="exam-day-toolkit"', 'id="exam-specs"', 'id="troubleshooting"', 'id="faq"', 'id="home-resources"'].map(id => html.indexOf(id));
assert.ok(journey.every((position, index) => position >= 0 && (index === 0 || position > journey[index - 1])), 'Tools, presets and help precede editorial guides');
assert.ok(html.indexOf('id="technical-trust"') > html.indexOf('id="portal-standards"'), 'Author and changelog follow main guidance');
const resources = html.match(/<section id="home-resources"[\s\S]*?<\/section>/)?.[0];
assert.ok(resources);
const guideLinks = [...resources.matchAll(/href="(\/blog\/[^\"]+)"/g)].map(m => m[1]);
assert.equal(guideLinks.length, 6);
assert.equal(new Set(guideLinks).size, guideLinks.length, 'Resource cards are unique');
assert.equal((html.match(/id="portal-standards"/g) || []).length, 1);
const result = await build({ stdin: { contents: "export { presetMode } from './src/utils/presetMode'; export { ALL_COMBINED_PRESETS } from './src/data/examPresets';", resolveDir: process.cwd() }, bundle: true, write: false, platform: 'node', format: 'esm' });
const { presetMode, ALL_COMBINED_PRESETS } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
assert.equal(presetMode(ALL_COMBINED_PRESETS.find(p => p.id === 'pan-card-photo-nsdl')), 'photo', 'Legacy photograph entries must select Photo mode');
assert.equal(presetMode(ALL_COMBINED_PRESETS.find(p => p.id === 'ssc-general')), 'signature');
assert.equal(presetMode(ALL_COMBINED_PRESETS.find(p => p.id === 'handwritten-declaration')), 'document');
console.log('PASS: focused H1, ten initial presets, six filters, complete preset HTML, unique guides, collapsed advanced settings, single FAQ/application schemas, diagnostics and author placement.');
